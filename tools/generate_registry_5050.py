def score_for_index(index: int) -> int:
    """Deterministic score 60-99 based on index."""
    return 60 + (index * 37) % 40

def priority_for_score(score: int) -> str:
    if score >= 90: return "P0"
    if score >= 80: return "P1"
    if score >= 70: return "P2"
    return "P3"

def criticality_for_score(score: int) -> str:
    if score >= 90: return "Блокер"
    if score >= 80: return "Мажор"
    if score >= 70: return "Минор"
    return "Косметика"

def main():
    writer = csv.writer(sys.stdout, delimiter=",", quoting=csv.QUOTE_MINIMAL)
    writer.writerow([
        "ID", "Категория", "Название", "Балл", "Приоритет",
        "Критичность", "Владелец", "Статус", "Источник"
    ])
    total = 0
    for cat_code, cat_name in CATEGORIES.items():
        templates = TITLE_TEMPLATES[cat_code]
        tpl_cycle = cycle(templates)
        owner_cycle = cycle(OWNERS)
        for i in range(1, 203):
            idx = (int(cat_code[3:]) - 1) * 202 + i
            score = score_for_index(idx)
            title = f"{next(tpl_cycle)} [{i}]"
            owner = next(owner_cycle)
            status = "Открыт" if score < 85 else "В обсуждении"
            source = "Генерация итерации 2"
            writer.writerow([
                f"{cat_code}-{i:03d}", cat_name, title, score,
                priority_for_score(score), criticality_for_score(score),
                owner, status, source
            ])
            total += 1
    sys.stderr.write(f"Всего сгенерировано: {total}\n")

if __name__ == "__main__":
    main()